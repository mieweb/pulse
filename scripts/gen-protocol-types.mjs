#!/usr/bin/env node
// Generates src/features/upload/protocol.gen.ts — TypeScript types for the upload protocol —
// from the JSON Schemas in the pinned pulsevault submodule (pulsevault-mieweb/protocol/schemas/),
// the protocol's single source (PROTOCOL.md §7). When a submodule bump changes the protocol, the
// types change with it and `tsc` shows what in the app needs to follow.
//
//   node scripts/gen-protocol-types.mjs          regenerate
//   node scripts/gen-protocol-types.mjs --check  fail if the file is out of date (CI)

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { compile } from 'json-schema-to-typescript';
import prettier from 'prettier';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const schemaDir = path.join(root, 'pulsevault-mieweb', 'protocol', 'schemas');
const outFile = path.join(root, 'src', 'features', 'upload', 'protocol.gen.ts');
const check = process.argv.includes('--check');

// Schema file → exported type name.
const TYPES = {
  'capabilities.schema.json': 'CapabilitiesResponse',
  'deep-link.schema.json': 'DeepLinkParams',
  'upload-metadata.schema.json': 'UploadMetadata',
  'beat-manifest.schema.json': 'BeatManifest',
  'capability-token.schema.json': 'CapabilityTokenClaims',
  'pulse-client.schema.json': 'PulseClientHeader',
};

let protocolVersion = 'unknown';
try {
  const pv = JSON.parse(
    await fs.readFile(path.join(root, 'pulsevault-mieweb', 'package.json'), 'utf8'),
  );
  protocolVersion = pv.pulseProtocol?.version ?? 'unknown';
} catch {
  // Submodule not checked out: the schema reads below fail with a clear message.
}

const blocks = [];
for (const [file, name] of Object.entries(TYPES)) {
  let schema;
  try {
    schema = JSON.parse(await fs.readFile(path.join(schemaDir, file), 'utf8'));
  } catch {
    console.error(
      `✗ ${path.relative(root, path.join(schemaDir, file))} not found — check out the submodule (git submodule update --init).`,
    );
    process.exit(1);
  }
  // The root type is named by `name`; drop `$id`/`title` so nothing else gets named after them.
  const { $id: _id, title: _title, ...rest } = schema;
  blocks.push(
    await compile(rest, name, {
      bannerComment: '',
      additionalProperties: false,
      strictIndexSignatures: true,
    }),
  );
}

const header = `// GENERATED by scripts/gen-protocol-types.mjs from pulsevault-mieweb/protocol/schemas/
// (upload protocol ${protocolVersion}). Do not edit: change the schema in pulsevault, bump the
// submodule, then run \`node scripts/gen-protocol-types.mjs\`.
`;
const source = await prettier.format(`${header}\n${blocks.join('\n')}`, {
  ...(await prettier.resolveConfig(outFile)),
  filepath: outFile,
});

const current = await fs.readFile(outFile, 'utf8').catch(() => null);
if (current === source) {
  if (check) console.log('✓ src/features/upload/protocol.gen.ts is up to date');
} else if (check) {
  console.error(
    '✗ src/features/upload/protocol.gen.ts is out of date with the pinned protocol — run `node scripts/gen-protocol-types.mjs` and commit it.',
  );
  process.exit(1);
} else {
  await fs.writeFile(outFile, source);
  console.log(`wrote ${path.relative(root, outFile)} (protocol ${protocolVersion})`);
}
