// @ts-check
// K5: @mieweb/capacitor-pulse's Package.swift, generated. A release declares each PulseKit
// xcframework as a remote `.binaryTarget(url:checksum:)` from the GitHub Release, with the
// checksum from the release's SHA256SUMS (the same value `swift package compute-checksum` prints).
// The committed file is this generator's placeholder output (version 0.0.0-dev, zero checksums);
// a test keeps the two identical, so the template lives here and only here.

import { parseSha256Sums } from './checksums.mjs';
import { XCFRAMEWORK_ZIP_SUFFIX, assertBaseUrl } from './release-assets.mjs';
import { assertVersion, TAG_PREFIX } from './release-version.mjs';

/**
 * @typedef {object} BinaryFramework
 * @property {string} name      The xcframework's name, which is also the binary target's name.
 * @property {string} checksum  SHA-256 of its release zip, lowercase hex.
 */

/** The xcframeworks of the M1 build, for the committed placeholder. A release lists its own. */
export const PLACEHOLDER_FRAMEWORKS = [
  'ExpoBrownfield',
  'ExpoFont',
  'ExpoImage',
  'ExpoMediaLibrary',
  'ExpoModulesCore',
  'ExpoModulesJSI',
  'ExpoModulesWorklets',
  'ExpoVideo',
  'PulseKit',
  'React',
  'ReactNativeDependencies',
  'SDWebImage',
  'SDWebImageAVIFCoder',
  'SDWebImageSVGCoder',
  'SDWebImageWebPCoder',
  'hermesvm',
  'libavif',
  'rnwhisper',
];

export const PLACEHOLDER_VERSION = '0.0.0-dev';
export const PLACEHOLDER_CHECKSUM = '0'.repeat(64);
export const PLACEHOLDER_BASE_URL = `https://github.com/mieweb/pulse/releases/download/${TAG_PREFIX}${PLACEHOLDER_VERSION}`;

/** @param {string} a @param {string} b */
const byName = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/**
 * The binary targets a release's SHA256SUMS describes: one per `<Name>.xcframework.zip`, sorted by
 * name. Other assets (the dSYMs, the all-in-one zip, the source map) are not binary targets.
 * @param {string} sumsText  SHA256SUMS
 * @returns {BinaryFramework[]}
 */
export function frameworksFromSums(sumsText) {
  const frameworks = parseSha256Sums(sumsText)
    .filter((e) => e.name.endsWith(XCFRAMEWORK_ZIP_SUFFIX))
    .map((e) => ({ name: e.name.slice(0, -XCFRAMEWORK_ZIP_SUFFIX.length), checksum: e.sha256 }))
    .sort((a, b) => byName(a.name, b.name));
  if (frameworks.length === 0) throw new Error('SHA256SUMS lists no *.xcframework.zip');
  if (!frameworks.some((f) => f.name === 'PulseKit')) {
    throw new Error('SHA256SUMS has no PulseKit.xcframework.zip');
  }
  return frameworks;
}

/** @returns {BinaryFramework[]} */
export function placeholderFrameworks() {
  return PLACEHOLDER_FRAMEWORKS.map((name) => ({ name, checksum: PLACEHOLDER_CHECKSUM }));
}

/**
 * Package.swift for a release (or, with the placeholder values, the committed file).
 * @param {{ version: string, baseUrl: string, frameworks: BinaryFramework[] }} release
 */
export function renderPackageSwift({ version, baseUrl, frameworks }) {
  assertVersion(version);
  assertBaseUrl(baseUrl);
  if (frameworks.length === 0) throw new Error('no frameworks to declare');
  const names = new Set();
  for (const f of frameworks) {
    // A Swift target name, and safe inside a string literal.
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(f.name)) throw new Error(`bad framework name "${f.name}"`);
    if (!/^[0-9a-f]{64}$/.test(f.checksum)) throw new Error(`${f.name}: bad checksum`);
    if (names.has(f.name)) throw new Error(`${f.name} is listed twice`);
    names.add(f.name);
  }
  const sorted = [...frameworks].sort((a, b) => byName(a.name, b.name));
  const table = sorted.map((f) => `  ("${f.name}", "${f.checksum}"),`).join('\n');

  return `// swift-tools-version: 5.9
// GENERATED by embed/scripts/write-package-swift.mjs: edit the template in
// embed/scripts/lib/release-package-swift.mjs, not this file.
import Foundation
import PackageDescription

// @mieweb/capacitor-pulse: the Capacitor transport over PulseKit (native-bridge.md §7.1).
//
// PulseKit ships as a set of xcframeworks, each a binary target here:
// - Release: the zips on the GitHub Release of PulseKit ${version}, checked against the SHA-256
//   each one has in that release's SHA256SUMS. The committed file is the 0.0.0-dev placeholder,
//   whose targets can't resolve; the release workflow writes the published one.
// - Development: PULSEKIT_LOCAL=<folder of *.xcframework> uses that folder instead, e.g. the
//   output of embed/scripts/package-ios.mjs. A relative folder is taken from this package's root.
//   SwiftPM accepts only paths relative to the package root, so the folder is rewritten relative
//   to it. Xcode reads the variable only when it was started with it (or from xcodebuild).
//
// .iOS(.v15) because Capacitor's CapApp-SPM declares 15; Pulse's floor (iOS 16.4, iPhone) is
// enforced at run time by info().supported.

let releaseVersion = "${version}"
let releaseBase = "${baseUrl}"

/// Each xcframework of the release and the SHA-256 of its zip.
let releaseFrameworks: [(name: String, checksum: String)] = [
${table}
]

let packageRoot = URL(fileURLWithPath: #filePath).deletingLastPathComponent().standardizedFileURL

/// \`target\` relative to \`base\`, with \`..\` where it leaves it (both absolute, standardized).
func relativePath(from base: URL, to target: URL) -> String {
  let from = base.pathComponents
  let to = target.pathComponents
  var shared = 0
  while shared < from.count, shared < to.count, from[shared] == to[shared] { shared += 1 }
  let up = Array(repeating: "..", count: from.count - shared)
  let path = (up + to[shared...]).joined(separator: "/")
  return path.isEmpty ? "." : path
}

func binaryTargets() -> [Target] {
  let env = ProcessInfo.processInfo.environment["PULSEKIT_LOCAL"] ?? ""
  if env.isEmpty {
    return releaseFrameworks.map {
      .binaryTarget(
        name: $0.name, url: "\\(releaseBase)/\\($0.name).xcframework.zip", checksum: $0.checksum)
    }
  }
  let folder = URL(fileURLWithPath: env, relativeTo: packageRoot).absoluteURL.standardizedFileURL
  let found = (try? FileManager.default.contentsOfDirectory(atPath: folder.path)) ?? []
  let names = found.filter { $0.hasSuffix(".xcframework") }.map { String($0.dropLast(12)) }.sorted()
  // An empty or missing folder keeps the release names, so the error names the expected paths.
  let local = relativePath(from: packageRoot, to: folder)
  return (names.isEmpty ? releaseFrameworks.map { $0.name } : names).map {
    .binaryTarget(name: $0, path: "\\(local)/\\($0).xcframework")
  }
}

let binaries = binaryTargets()

let package = Package(
  name: "MiewebCapacitorPulse",
  platforms: [.iOS(.v15)],
  products: [
    // Capacitor's CLI names the product after the npm package: @mieweb/capacitor-pulse.
    .library(name: "MiewebCapacitorPulse", targets: ["PulsePlugin"])
  ],
  dependencies: [
    .package(url: "https://github.com/ionic-team/capacitor-swift-pm.git", from: "8.0.0")
  ],
  targets: binaries + [
    .target(
      name: "PulsePlugin",
      dependencies: [.product(name: "Capacitor", package: "capacitor-swift-pm")]
        + binaries.map { .target(name: $0.name) },
      path: "ios/Sources/PulsePlugin"
    )
  ]
)
`;
}

/** The committed Package.swift. */
export function placeholderPackageSwift() {
  return renderPackageSwift({
    version: PLACEHOLDER_VERSION,
    baseUrl: PLACEHOLDER_BASE_URL,
    frameworks: placeholderFrameworks(),
  });
}
