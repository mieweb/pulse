// @ts-check
// cordova-plugin-pulse's PulseKit.podspec, generated. CocoaPods takes one source per pod, so a
// release points it at the all-in-one zip (every xcframework at its top level) with that zip's
// SHA-256 from the release's SHA256SUMS; CocoaPods checks the download against it. The committed
// file is this generator's placeholder output (version 0.0.0-dev, zero checksum); a test keeps the
// two identical, so the template lives here and only here.

import { parseSha256Sums } from './checksums.mjs';
import { XCFRAMEWORKS_ZIP, assertBaseUrl } from './release-assets.mjs';
import { PLACEHOLDER_BASE_URL, PLACEHOLDER_VERSION } from './release-package-swift.mjs';
import { assertVersion } from './release-version.mjs';

export const PLACEHOLDER_SHA256 = '0'.repeat(64);

/**
 * The all-in-one zip's SHA-256 from a release's SHA256SUMS.
 * @param {string} sumsText
 */
export function xcframeworksZipSha256(sumsText) {
  const entry = parseSha256Sums(sumsText).find((e) => e.name === XCFRAMEWORKS_ZIP);
  if (!entry) throw new Error(`SHA256SUMS has no ${XCFRAMEWORKS_ZIP}`);
  return entry.sha256;
}

/**
 * PulseKit.podspec for a release (or, with the placeholder values, the committed file).
 * @param {{ version: string, baseUrl: string, sha256: string }} release
 */
export function renderPodspec({ version, baseUrl, sha256 }) {
  assertVersion(version);
  assertBaseUrl(baseUrl);
  if (!/^[0-9a-f]{64}$/.test(sha256)) throw new Error(`"${sha256}" is not a SHA-256`);
  const url = `${baseUrl}/${XCFRAMEWORKS_ZIP}`;

  return `# PulseKit's xcframeworks for cordova-plugin-pulse (plugin.xml points the host's Podfile here).
# GENERATED by embed/scripts/write-podspec.mjs: edit the template in
# embed/scripts/lib/release-podspec.mjs, not this file.
#
# Release: the zip on the GitHub Release of PulseKit ${version} that holds every *.xcframework at
# its top level, checked against its SHA-256 from that release's SHA256SUMS. The committed file is
# the 0.0.0-dev placeholder, which can't download; the release workflow writes the published one.
#
# Development: PULSEKIT_LOCAL=<folder of *.xcframework> (or a .zip of them) builds against a local
# PulseKit. A folder is zipped into the system temp folder under a name that fingerprints every
# file in its frameworks (path, mode and contents), so a rebuild that overwrites a nested binary or
# resource in place makes a new zip, at a new URL, instead of reusing the old one.

require 'digest'
require 'tmpdir'

PULSEKIT_RELEASE_URL = '${url}'
PULSEKIT_RELEASE_SHA256 = '${sha256}'

def pulsekit_source
  local = ENV.fetch('PULSEKIT_LOCAL', '')
  return { :http => PULSEKIT_RELEASE_URL, :sha256 => PULSEKIT_RELEASE_SHA256 } if local.empty?

  path = File.expand_path(local)
  return { :http => "file://#{path}" } if File.file?(path)

  frameworks = Dir.exist?(path) ? Dir.children(path).select { |n| n.end_with?('.xcframework') }.sort : []
  raise "PULSEKIT_LOCAL=#{path} holds no .xcframework" if frameworks.empty?

  entries = Dir.glob(frameworks.map { |n| "#{n}/**/*" }, File::FNM_DOTMATCH, base: path)
  entries = (frameworks + entries).reject { |r| ['.', '..'].include?(File.basename(r)) }.uniq.sort
  fingerprint = Digest::SHA256.new
  entries.each do |rel|
    full = File.join(path, rel)
    stat = File.lstat(full)
    body = if stat.symlink? then "link:#{File.readlink(full)}"
           elsif stat.file? then "file:#{Digest::SHA256.file(full).hexdigest}"
           else 'dir'
           end
    fingerprint << "#{rel}\\0#{stat.mode.to_s(8)}\\0#{body}\\n"
  end
  prefix = File.join(Dir.tmpdir, "pulsekit-local-#{Digest::SHA256.hexdigest(path)[0, 12]}")
  zip = "#{prefix}-#{fingerprint.hexdigest[0, 16]}.zip"
  unless File.exist?(zip)
    Dir.glob("#{prefix}-*.zip").each { |old| File.delete(old) }
    partial = "#{zip}.partial"
    File.delete(partial) if File.exist?(partial)
    Dir.chdir(path) { system('zip', '-qry', partial, *frameworks) || raise("Couldn't zip #{path}") }
    File.rename(partial, zip)
  end
  { :http => "file://#{zip}" }
end

Pod::Spec.new do |s|
  s.name = 'PulseKit'
  # Lockstep with the embed packages (AD18).
  s.version = '${version}'
  s.summary = 'Pulse, the video recorder and editor, as frameworks a host app presents.'
  s.homepage = 'https://github.com/mieweb/pulse'
  s.author = 'mieweb'
  s.source = pulsekit_source
  # Capacitor's floor; Pulse's own (iOS 16.4, iPhone) is checked at run time by info().supported.
  s.platform = :ios, '15.0'
  s.vendored_frameworks = '*.xcframework'
end
`;
}

/** The committed PulseKit.podspec. */
export function placeholderPodspec() {
  return renderPodspec({
    version: PLACEHOLDER_VERSION,
    baseUrl: PLACEHOLDER_BASE_URL,
    sha256: PLACEHOLDER_SHA256,
  });
}
